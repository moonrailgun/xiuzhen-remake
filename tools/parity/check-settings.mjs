import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1100, height: 700 }, deviceScaleFactor: 1 })
const errs = []
p.on('pageerror', (e) => errs.push(String(e)))
await p.goto('http://localhost:5273', { waitUntil: 'networkidle' })
await p.evaluate(() => localStorage.clear())
await p.reload({ waitUntil: 'networkidle' })
await p.fill('#playername', '测试')
await p.click('a[onclick="sendCreatePlayer()"]')
await p.waitForTimeout(400)
await p.click('a[onclick="openSettings()"]')
await p.waitForTimeout(300)
console.log('设置面板:', (await p.locator('#lwindowcontent').textContent() || '').replace(/\s+/g, ' ').slice(0, 90))
await p.click('a[onclick="setRate(10)"]')
await p.waitForTimeout(400)
console.log('倍速切换后 rate =', await p.evaluate(() => JSON.parse(localStorage.getItem('xiuzhen.save')).state.clock.rate))
await p.screenshot({ path: 'tools/parity/shots/play-8-settings.png' })
console.log('报错:', errs.length ? errs[0] : '无')
await b.close()
